"""Консервативный маршрутизатор юридических запросов без правовой базы."""

from __future__ import annotations

import re

from .domain import Role


_LEGAL_TERMS = re.compile(
    r"\b(?:закон\w*|фз|стать[яеию]|кодекс\w*|юридическ\w*|"
    r"правов\w*|право|договор\w*|налог\w*|штраф\w*|суд\w*|"
    r"обжалова\w*|увол\w*|неустойк\w*|компенсац\w*|"
    r"ответственност\w*|трудов\w*|банкротств\w*|"
    r"блокир\w*|списа\w*|возврат\w*|задолженност\w*|"
    r"согласи[еяю]|"
    r"152\s*[-–]?\s*фз|161\s*[-–]?\s*фз|115\s*[-–]?\s*фз|"
    r"тк\s*рф|гк\s*рф)\b",
    re.IGNORECASE,
)


def is_legal_question(query: str) -> bool:
    """Сигнал для отказа по умолчанию; не заменяет юридическую классификацию."""
    return bool(_LEGAL_TERMS.search(query))


def source_required_answer(role: Role) -> str:
    """Показывает маршрут проверки без утверждений о содержании нормы."""
    answer = (
        "Я не могу подтвердить действующую норму, её редакцию и применимость "
        "к вашему случаю. Проверьте текст в официальном источнике: "
        "https://pravo.gov.ru/. "
    )
    if role is Role.EMPLOYEE:
        return answer + (
            "Для рабочего вопроса также нужен утверждённый внутренний документ "
            "и проверка уполномоченным HR- или юридическим специалистом."
        )
    return answer + (
        "Для банковского вопроса проверьте относящиеся к нему акты "
        "на https://www.cbr.ru/banking_sector/acts/ и условия вашего "
        "договора; правовой вывод должен проверить специалист."
    )
